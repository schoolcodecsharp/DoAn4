test('customer books tour; admin confirms and cancels; history retained',async({page,browser})=>{
  await login(page);
  await page.goto('/tours?keyword='+encodeURIComponent(env.E2E_TAG!));
  await page.getByRole('link',{name:env.E2E_TAG!,exact:true}).click();
  await page.getByRole('link',{name:'Đặt tour',exact:true}).click();
  await page.getByLabel('Số khách',{exact:true}).fill('2');
  const created=page.waitForResponse(r=>r.url().endsWith('/api/account/bookings/tours')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Xác nhận yêu cầu đặt chỗ'}).click();
  const response=await created; expect(response.status()).toBe(201); const order=await response.json();
  await expect(page.getByText('YÊU CẦU ĐÃ ĐƯỢC LƯU')).toBeVisible();
  await page.getByRole('link',{name:'Xem đơn đặt của tôi'}).click();
  await expect(page.locator('.booking-record').filter({hasText:env.E2E_TAG})).toContainText('Chờ xác nhận');
  const context=await browser.newContext({baseURL:'http://127.0.0.1:5173'});const admin=await context.newPage();
  admin.on('dialog',d=>d.accept()); await login(admin,true);
  await admin.getByRole('link',{name:'Đơn tour',exact:true}).click();
  const row=admin.getByTestId('order-'+order.id);
  await row.getByRole('button',{name:'Đã xác nhận',exact:true}).click();
  await expect(row.getByRole('button',{name:'Hoàn thành',exact:true})).toBeVisible();
  await row.getByRole('button',{name:'Đã hủy',exact:true}).click();
  await expect(row).toContainText('Đã kết thúc');
  await page.reload();
  await expect(page.locator('.booking-record').filter({hasText:env.E2E_TAG})).toContainText('Đã hủy');
  await context.close();
});
