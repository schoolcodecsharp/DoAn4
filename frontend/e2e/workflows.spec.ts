import { test, expect, type Page } from '@playwright/test';

const env=process.env;
test.beforeEach(async({page})=>{
  if(!env.E2E_TAG) throw new Error('Run through tests/AdminSmoke --browser to create and clean disposable fixtures.');
  // Province provider is the only stub: keep browser tests independent of third-party availability.
  await page.route('https://provinces.open-api.vn/**',route=>route.fulfill({json:[{code:22,name:'Tỉnh Quảng Ninh'},{code:48,name:'Thành phố Đà Nẵng'}]}));
  page.on('dialog',dialog=>dialog.accept());
});
async function login(page:Page,admin=false) {
  await page.goto('/login');
  await page.getByLabel('Email',{exact:true}).fill((admin?env.E2E_ADMIN_EMAIL:env.E2E_EMAIL)!);
  await page.locator('input[autocomplete="current-password"]').fill(env.E2E_PASSWORD!);
  await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
  await expect(page).toHaveURL(admin?/\/admin$/:/\/account$/);
}
